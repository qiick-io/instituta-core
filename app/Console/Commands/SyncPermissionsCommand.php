<?php

declare(strict_types=1);

namespace App\Console\Commands;

use App\Enums\PermissionEnum;
use App\Enums\RoleEnum;
use App\Models\Role;
use Database\Seeders\RoleSeeder;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;
use Spatie\Permission\Models\Permission;
use Spatie\Permission\PermissionRegistrar;
use Symfony\Component\Console\Attribute\AsCommand;

/**
 * Sync PermissionEnum cases to the database and regenerate the TypeScript enum.
 */
#[AsCommand(name: 'instituta:sync-permissions')]
class SyncPermissionsCommand extends Command
{
    protected $signature = 'instituta:sync-permissions {--prune : Remove permissions that are no longer defined in PermissionEnum}';

    protected $description = 'Sync PermissionEnum cases to the database and generate TypeScript enum';

    /**
     * Sync PermissionEnum cases to the database and regenerate the TypeScript enum.
     */
    public function handle(): int
    {
        app(PermissionRegistrar::class)->forgetCachedPermissions();

        $guard = config('auth.defaults.guard', 'web');
        $enumValues = PermissionEnum::values();
        $createdNames = [];

        foreach ($enumValues as $name) {
            $permission = Permission::query()->firstOrCreate(
                ['name' => $name, 'guard_name' => $guard],
            );

            if ($permission->wasRecentlyCreated) {
                $createdNames[] = $name;
            }
        }

        $this->info(sprintf('Synced %d permissions.', count($enumValues)));
        $this->grantCreatedPermissionsToAdmin($createdNames, $guard);

        if ($this->option('prune')) {
            $deleted = Permission::query()
                ->where('guard_name', $guard)
                ->whereNotIn('name', $enumValues)
                ->delete();

            $this->info(sprintf('Pruned %d stale permissions.', $deleted));
        }

        $this->generateTypeScriptEnum();
        app(PermissionRegistrar::class)->forgetCachedPermissions();

        return self::SUCCESS;
    }

    /**
     * Give the built-in `admin` role every permission this sync just created.
     *
     * Matches {@see RoleSeeder} (admin holds every permission) on
     * upgraded installs. Only new rows are granted, so permissions an operator
     * removed from admin stay removed. Super-admin needs no grant: it bypasses
     * permission checks via Gate::before. On a fresh install the role does not
     * exist yet and RoleSeeder grants everything.
     *
     * @param  list<string>  $createdNames
     */
    private function grantCreatedPermissionsToAdmin(array $createdNames, string $guard): void
    {
        if ($createdNames === []) {
            return;
        }

        $admin = Role::query()
            ->where('name', RoleEnum::Admin->value)
            ->where('guard_name', $guard)
            ->first();

        if ($admin === null) {
            return;
        }

        $admin->givePermissionTo($createdNames);

        $this->info(sprintf(
            'Granted %d new permission(s) to %s: %s',
            count($createdNames),
            RoleEnum::Admin->value,
            implode(', ', $createdNames),
        ));
    }

    /**
     * Write the generated PermissionEnum TypeScript file to resources/js/enums.
     */
    protected function generateTypeScriptEnum(): void
    {
        $lines = [
            '/**',
            ' * Auto-generated by `php artisan instituta:sync-permissions`. Do not edit manually.',
            ' */',
            'export enum PermissionEnum {',
        ];

        foreach (PermissionEnum::cases() as $case) {
            $lines[] = sprintf("    %s = '%s',", $case->name, $case->value);
        }

        $lines[] = '}';
        $lines[] = '';
        // ponytail: match the Oxfmt printWidth (80) so sync does not fail format:check
        $lines[] = 'export const PermissionEnumValues = Object.values(';
        $lines[] = '    PermissionEnum,';
        $lines[] = ') as PermissionEnum[];';
        $lines[] = '';

        $path = resource_path('js/enums/permission-enum.ts');
        File::ensureDirectoryExists(dirname($path));
        File::put($path, implode(PHP_EOL, $lines));

        $this->info("Generated {$path}");
    }
}
